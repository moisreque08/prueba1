    /**
    * Maneja la acción de agregar una conexión entre estaciones.
    * @param evt Evento de acción
    */
    private void btnAgregarConexionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarConexionActionPerformed
        if (grafo.getNumEstaciones() < 2) {
            javax.swing.JOptionPane.showMessageDialog(this, "Se necesitan al menos 2 estaciones");
            return;
        }

        EDD.Lista<EDD.Estacion> estaciones = grafo.getTodasEstaciones();
        String[] ids = new String[estaciones.getTamaño()];
        for (int i = 0; i < estaciones.getTamaño(); i++) {
            ids[i] = estaciones.obtener(i).getId();
        }

        javax.swing.JComboBox<String> cboO = new javax.swing.JComboBox<>(ids);
        javax.swing.JComboBox<String> cboD = new javax.swing.JComboBox<>(ids);
        javax.swing.JTextField txtT = new javax.swing.JTextField("2");

        javax.swing.JPanel panel = new javax.swing.JPanel(new java.awt.GridLayout(3, 2, 5, 5));
        panel.add(new javax.swing.JLabel("Origen:"));
        panel.add(cboO);
        panel.add(new javax.swing.JLabel("Destino:"));
        panel.add(cboD);
        panel.add(new javax.swing.JLabel("Tiempo (min):"));
        panel.add(txtT);

        int r = javax.swing.JOptionPane.showConfirmDialog(this, panel, 
            "Agregar Conexión", javax.swing.JOptionPane.OK_CANCEL_OPTION);

        if (r == javax.swing.JOptionPane.OK_OPTION) {
            try {
                String o = (String) cboO.getSelectedItem();
                String d = (String) cboD.getSelectedItem();
                double t = Double.parseDouble(txtT.getText().trim());

                if (o.equals(d)) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Origen y destino deben ser diferentes");
                    return;
                }

                if (grafo.agregarArista(o, d, t)) {
                    GestorArchivo.marcarCambios();
                    actualizarInfo();
                    txtResultados1.append("Conexión agregada: " + o + " - " + d + " (" + t + " min)\n");
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Ya existe esa conexión");
                }
            } catch (NumberFormatException e) {
                javax.swing.JOptionPane.showMessageDialog(this, "Tiempo inválido");
            }
        }
    }//GEN-LAST:event_btnAgregarConexionActionPerformed

    /**
    * Maneja la acción de eliminar una conexión.
    * @param evt Evento de acción
    */
    private void btnEliminarConexionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarConexionActionPerformed
        if (grafo.getNumAristas() == 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "No hay conexiones");
            return;
        }

        EDD.Lista<EDD.Arista> aristas = grafo.getAristas();
        String[] ops = new String[aristas.getTamaño()];
        for (int i = 0; i < aristas.getTamaño(); i++) {
            EDD.Arista a = aristas.obtener(i);
            ops[i] = a.getOrigen().getId() + " - " + a.getDestino().getId();
        }

        String sel = (String) javax.swing.JOptionPane.showInputDialog(this,
            "Seleccione la conexión a eliminar:", "Eliminar Conexión",
            javax.swing.JOptionPane.QUESTION_MESSAGE, null, ops, ops[0]);

        if (sel != null) {
            String[] p = sel.split(" - ");
            if (grafo.eliminarArista(p[0], p[1])) {
                GestorArchivo.marcarCambios();
                actualizarInfo();
                txtResultados1.append("Conexión eliminada: " + sel + "\n");
            }
        }
    }//GEN-LAST:event_btnEliminarConexionActionPerformed

    /**
    * Maneja la acción de calcular la ruta más corta.
    * @param evt Evento de acción
    */
    private void btnCalcularRutaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularRutaActionPerformed
        String o = (String) cmbOrigen.getSelectedItem();
        String d = (String) cmbDestino.getSelectedItem();

        if (o == null || d == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Seleccione origen y destino");
            return;
        }
        if (o.equals(d)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Origen y destino deben ser diferentes");
            return;
        }

        txtResultados1.append("\nRUTA MÁS CORTA\n");
        txtResultados1.append("De: " + o + " a: " + d + "\n");

        EDD.Grafo.ResultadoDijkstra res = grafo.rutaMasCorta(o, d);
        if (res.hayRuta()) {
            txtResultados1.append("Tiempo total: " + res.getDistancia() + " min\n");
            txtResultados1.append("Ruta: ");
            for (int i = 0; i < res.getRuta().getTamaño(); i++) {
                if (i > 0) txtResultados1.append(" → ");
                txtResultados1.append(res.getRuta().obtener(i).getId());
            }
            txtResultados1.append("\n\n");
        } else {
            txtResultados1.append("No hay ruta disponible\n\n");
        }
    }//GEN-LAST:event_btnCalcularRutaActionPerformed

    /**
    * Maneja la acción de detectar subredes.
    * @param evt Evento de acción
    */
    private void btnSubredesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubredesActionPerformed
        txtResultados1.append("\nSUBREDES / COMPONENTES CONEXOS\n");
    
        EDD.Lista<EDD.Lista<EDD.Estacion>> subredes = grafo.encontrarSubredes();
        if (subredes.getTamaño() == 0) {
            txtResultados1.append("No se encontraron subredes\n\n");
        } else {
            txtResultados1.append("Se encontraron " + subredes.getTamaño() + " subredes:\n\n");
            for (int i = 0; i < subredes.getTamaño(); i++) {
                EDD.Lista<EDD.Estacion> sr = subredes.obtener(i);
                txtResultados1.append("Subred " + (i+1) + " (" + sr.getTamaño() + " estaciones):\n");
                for (int j = 0; j < sr.getTamaño(); j++) {
                    txtResultados1.append("  • " + sr.obtener(j).getId() + " - " + sr.obtener(j).getNombre() + "\n");
                }
                txtResultados1.append("\n");
            }
        }
    }//GEN-LAST:event_btnSubredesActionPerformed

